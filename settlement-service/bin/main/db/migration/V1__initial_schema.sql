-- ==========================================================================
-- Settlement Service — initial schema (PostgreSQL)
-- Applied by Flyway under the 'prod' profile. The 'dev' profile uses H2 with
-- Hibernate ddl-auto=update instead.
-- All monetary columns are BIGINT minor units.
-- ==========================================================================

CREATE TABLE settlement_batches (
    id                   VARCHAR(40)  PRIMARY KEY,
    merchant_id          VARCHAR(255) NOT NULL,
    currency             VARCHAR(3)   NOT NULL,
    schedule_type        VARCHAR(20),
    period_start         TIMESTAMP,
    period_end           TIMESTAMP,
    status               VARCHAR(20)  NOT NULL,
    gross_minor          BIGINT       NOT NULL DEFAULT 0,
    refunds_minor        BIGINT       NOT NULL DEFAULT 0,
    fees_minor           BIGINT       NOT NULL DEFAULT 0,
    interchange_minor    BIGINT       NOT NULL DEFAULT 0,
    chargebacks_minor    BIGINT       NOT NULL DEFAULT 0,
    adjustments_minor    BIGINT       NOT NULL DEFAULT 0,
    reserve_minor        BIGINT       NOT NULL DEFAULT 0,
    settlement_fee_minor BIGINT       NOT NULL DEFAULT 0,
    net_minor            BIGINT       NOT NULL DEFAULT 0,
    ledger_journal_id    VARCHAR(255),
    approved_by          VARCHAR(255),
    approved_at          TIMESTAMP,
    closed_at            TIMESTAMP,
    failure_reason       VARCHAR(512),
    created_at           TIMESTAMP,
    updated_at           TIMESTAMP,
    version              BIGINT
);
CREATE INDEX idx_batch_merchant ON settlement_batches (merchant_id);
CREATE INDEX idx_batch_status   ON settlement_batches (status);

CREATE TABLE settlement_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id        VARCHAR(40),
    merchant_id     VARCHAR(255) NOT NULL,
    type            VARCHAR(30)  NOT NULL,
    source_type     VARCHAR(30),
    source_id       VARCHAR(255),
    amount_minor    BIGINT       NOT NULL,
    currency        VARCHAR(3)   NOT NULL,
    effective_at    TIMESTAMP    NOT NULL,
    idempotency_key VARCHAR(255) UNIQUE,
    created_at      TIMESTAMP,
    updated_at      TIMESTAMP,
    version         BIGINT
);
CREATE INDEX idx_item_batch    ON settlement_items (batch_id);
CREATE INDEX idx_item_merchant ON settlement_items (merchant_id);
CREATE INDEX idx_item_source   ON settlement_items (source_type, source_id);

CREATE TABLE payouts (
    id                VARCHAR(40)  PRIMARY KEY,
    batch_id          VARCHAR(40)  NOT NULL,
    merchant_id       VARCHAR(255) NOT NULL,
    payout_account_id VARCHAR(255),
    amount_minor      BIGINT       NOT NULL,
    currency          VARCHAR(3)   NOT NULL,
    rail              VARCHAR(20),
    status            VARCHAR(20)  NOT NULL,
    provider_ref      VARCHAR(255),
    idempotency_key   VARCHAR(255) UNIQUE,
    ledger_journal_id VARCHAR(255),
    attempt_count     INTEGER      NOT NULL DEFAULT 0,
    next_retry_at     TIMESTAMP,
    failure_code      VARCHAR(255),
    failure_reason    VARCHAR(512),
    failure_category  VARCHAR(20),
    scheduled_at      TIMESTAMP,
    submitted_at      TIMESTAMP,
    paid_at           TIMESTAMP,
    created_at        TIMESTAMP,
    updated_at        TIMESTAMP,
    version           BIGINT
);
CREATE INDEX idx_payout_batch      ON payouts (batch_id);
CREATE INDEX idx_payout_merchant   ON payouts (merchant_id);
CREATE INDEX idx_payout_status     ON payouts (status);
CREATE INDEX idx_payout_next_retry ON payouts (next_retry_at);

CREATE TABLE payout_returns (
    id                 VARCHAR(40)  PRIMARY KEY,
    payout_id          VARCHAR(40)  NOT NULL,
    reason_code        VARCHAR(255),
    reason_description VARCHAR(512),
    amount_minor       BIGINT       NOT NULL,
    currency           VARCHAR(3),
    returned_at        TIMESTAMP    NOT NULL,
    ledger_journal_id  VARCHAR(255),
    created_at         TIMESTAMP,
    updated_at         TIMESTAMP,
    version            BIGINT
);
CREATE INDEX idx_return_payout ON payout_returns (payout_id);

CREATE TABLE reserves (
    id             VARCHAR(40)  PRIMARY KEY,
    merchant_id    VARCHAR(255) NOT NULL,
    kind           VARCHAR(20)  NOT NULL,
    rate_bps       INTEGER,
    amount_minor   BIGINT       NOT NULL,
    released_minor BIGINT       NOT NULL DEFAULT 0,
    currency       VARCHAR(3)   NOT NULL,
    source_batch_id VARCHAR(40),
    hold_until     DATE,
    status         VARCHAR(20)  NOT NULL,
    ledger_hold_id VARCHAR(255),
    released_at    TIMESTAMP,
    created_at     TIMESTAMP,
    updated_at     TIMESTAMP,
    version        BIGINT
);
CREATE INDEX idx_reserve_merchant   ON reserves (merchant_id);
CREATE INDEX idx_reserve_status     ON reserves (status);
CREATE INDEX idx_reserve_hold_until ON reserves (hold_until);

CREATE TABLE adjustments (
    id                      VARCHAR(40)  PRIMARY KEY,
    merchant_id             VARCHAR(255) NOT NULL,
    type                    VARCHAR(30)  NOT NULL,
    amount_minor            BIGINT       NOT NULL,
    currency                VARCHAR(3)   NOT NULL,
    reason_code             VARCHAR(255) NOT NULL,
    description             VARCHAR(1024),
    status                  VARCHAR(20)  NOT NULL,
    required_approval_level VARCHAR(20),
    requested_by            VARCHAR(255),
    approved_by             VARCHAR(255),
    approved_at             TIMESTAMP,
    applied_batch_id        VARCHAR(40),
    applied_at              TIMESTAMP,
    created_at              TIMESTAMP,
    updated_at              TIMESTAMP,
    version                 BIGINT
);
CREATE INDEX idx_adjustment_merchant ON adjustments (merchant_id);
CREATE INDEX idx_adjustment_status   ON adjustments (status);

CREATE TABLE outbox_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type     VARCHAR(60)  NOT NULL,
    aggregate_type VARCHAR(40)  NOT NULL,
    aggregate_id   VARCHAR(40)  NOT NULL,
    payload        TEXT         NOT NULL,
    status         VARCHAR(20)  NOT NULL,
    attempts       INTEGER      NOT NULL DEFAULT 0,
    published_at   TIMESTAMP,
    last_error     VARCHAR(512),
    created_at     TIMESTAMP,
    updated_at     TIMESTAMP,
    version        BIGINT
);
CREATE INDEX idx_outbox_status    ON outbox_events (status);
CREATE INDEX idx_outbox_aggregate ON outbox_events (aggregate_type, aggregate_id);

CREATE TABLE idempotency_records (
    idempotency_key     VARCHAR(120) PRIMARY KEY,
    request_fingerprint VARCHAR(128),
    resource_type       VARCHAR(40),
    resource_id         VARCHAR(40),
    response_status     INTEGER,
    response_body       TEXT,
    created_at          TIMESTAMP,
    updated_at          TIMESTAMP,
    version             BIGINT
);
